import fs from "node:fs/promises"
import path from "node:path"

const mode = process.env.PLASMO_PUBLIC_PHOTOSWEEP_ALLOW_DEV_ENTITLEMENT
const allowDev = mode === "1"
const includeDevKey = allowDev || mode === "test"
const output = path.resolve("lib/generated/build-flags.ts")

await fs.mkdir(path.dirname(output), { recursive: true })
await fs.writeFile(
  output,
  `// Generated by tools/write-build-flags.mjs. Do not edit.\nexport const ALLOW_DEV_ENTITLEMENT = ${allowDev}\nexport const DEV_ENTITLEMENT_STORAGE_KEY = ${includeDevKey ? '"photoSweepDevEntitlement"' : "undefined"}\n`
)
